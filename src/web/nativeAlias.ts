/**
 * `../native` / `../../native` / `./native` 等の相対パスによる native モジュール
 * import にマッチする正規表現。nativeShim 自身 (`./nativeShim`) や
 * types.ts にはマッチしない。
 *
 * 注意: `.*\/native$` としてしまうと「../native」の様にドットの直後に
 * native が来る形式 (フロントエンドの実際の import 形式) にマッチしない。
 * 常に `(ドット+スラッシュ)+native` で終端まで一致する形が正しい。
 */
export const NATIVE_ALIAS_FIND = /^(\.\.?\/)+native$/;

